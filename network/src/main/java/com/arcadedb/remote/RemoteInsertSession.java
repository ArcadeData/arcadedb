package com.arcadedb.remote;

import com.arcadedb.log.LogManager;
import com.arcadedb.serializer.json.JSONArray;
import com.arcadedb.serializer.json.JSONObject;

import java.net.URI;
import java.net.http.WebSocket;
import java.time.Duration;
import java.util.List;
import java.util.concurrent.CompletionStage;
import java.util.concurrent.LinkedBlockingQueue;
import java.util.concurrent.TimeUnit;
import java.util.function.Consumer;
import java.util.logging.Level;

/**
 * The Java client for the duplex insert session on {@code /ws} (issue #7403), opened with
 * {@link RemoteDatabase#newInsertSession()}.
 * <p>
 * It is the counterpart of {@code RemoteGrpcDatabase.insertBidirectional*}, and what {@link RemoteGraphBatch}'s
 * progress callback structurally cannot offer: the caller sees the acknowledgement of chunk <i>n</i> and then
 * decides what to send next, including whether to {@link #commit()} or {@link #rollback()} at all. Before this
 * class the only way to use the feature from Java was to bring a WebSocket client and hand-write the frames.
 * <p>
 * Built on the JDK's own {@link WebSocket}, so it adds no dependency. {@link #sendChunk} is synchronous: it
 * writes the frame and returns the {@code batchAck} the server answered it with, which is the shape a bulk
 * loader reading from a source wants. A client that would rather be told than ask registers a callback with
 * {@link Builder#onBatchAck(Consumer)}; it is invoked, on the calling thread, with every acknowledgement before
 * {@code sendChunk} returns it.
 * <p>
 * <b>Not thread safe</b>, exactly as {@link RemoteDatabase} is not: one session belongs to one thread. The
 * protocol itself allows a client to pipeline frames, which this class deliberately does not do - a loader that
 * wants the acknowledgements to mean anything has to look at them.
 *
 * @author Arcade Data Ltd
 */
public class RemoteInsertSession implements AutoCloseable {
  /** What the server answers a {@code commit}/{@code rollback} frame on an externally-managed transaction with. */
  public static final String OUTCOME_DETACHED = "detached";

  private final WebSocket                     webSocket;
  private final LinkedBlockingQueue<String>   incoming;
  private final RemoteWebSocketListener       listener;
  private final Consumer<JSONObject>          ackListener;
  private final long                          timeoutMs;
  private final String                        sessionId;
  private final String                        databaseName;
  private final String                        transactionMode;
  private final String                        externalTransactionId;
  private       long                          chunkSeq;
  private       boolean                       open = true;

  RemoteInsertSession(final WebSocket webSocket, final RemoteWebSocketListener listener, final JSONObject started,
      final Consumer<JSONObject> ackListener, final long timeoutMs) {
    this.webSocket = webSocket;
    this.listener = listener;
    this.incoming = listener.getQueue();
    this.ackListener = ackListener;
    this.timeoutMs = timeoutMs;
    this.sessionId = started.getString("sessionId");
    this.databaseName = started.getString("database", null);
    this.transactionMode = started.getString("transactionMode", null);
    this.externalTransactionId = started.getString("transactionId", null);
  }

  /** The id this session is known by on the server, generated by it unless the client chose one. */
  public String getSessionId() {
    return sessionId;
  }

  public String getDatabaseName() {
    return databaseName;
  }

  /** The commit policy the server echoed back in its {@code started} frame, which may differ from the alias sent. */
  public String getTransactionMode() {
    return transactionMode;
  }

  /** The externally-managed transaction this session joined, or {@code null} when it manages its own. */
  public String getExternalTransactionId() {
    return externalTransactionId;
  }

  /** How many chunks have been sent. The next one is this plus one. */
  public long getLastChunkSeq() {
    return chunkSeq;
  }

  public boolean isOpen() {
    return open;
  }

  /**
   * Sends one chunk and returns the {@code batchAck} the server answered with, after handing it to the callback
   * registered with {@link Builder#onBatchAck(Consumer)} if there is one.
   * <p>
   * The sequence number is managed here and starts at 1: the replay and gap rules the server enforces are about
   * a client resending a chunk, not about a client choosing arbitrary numbers, and getting them wrong is a
   * protocol error rather than anything a loader wants to think about.
   *
   * @throws RemoteException when the server refused the chunk. The session stays open - a chunk refused for its
   *                         size or its sequence leaves the watermark where it was - so the caller may split the
   *                         batch and send it again
   */
  public JSONObject sendChunk(final List<JSONObject> records) {
    final JSONArray array = new JSONArray();
    for (final JSONObject record : records)
      array.put(record);
    return sendChunk(array);
  }

  /** {@link #sendChunk(List)} for a caller that already has the records as a {@link JSONArray}. */
  public JSONObject sendChunk(final JSONArray records) {
    checkOpen();

    final long seq = chunkSeq + 1;
    final JSONObject frame = new JSONObject();
    frame.put("action", "chunk");
    frame.put("sessionId", sessionId);
    frame.put("chunkSeq", seq);
    frame.put("records", records);

    final JSONObject ack = exchange(frame, "batchAck");
    // Advanced only once the server has acknowledged it, so a refused chunk can be resent under the same
    // sequence - which is what makes "split the batch and try again" work after a rows-per-chunk refusal.
    chunkSeq = seq;

    if (ackListener != null)
      ackListener.accept(ack);
    return ack;
  }

  /**
   * Ends the session and commits what it wrote, returning the {@code committed} frame.
   * <p>
   * A session that joined an externally-managed transaction commits nothing here: the answer's {@code outcome}
   * is {@link #OUTCOME_DETACHED} and the rows become durable only when the caller commits that transaction over
   * HTTP - {@link RemoteDatabase#commit()} on the database the session was opened from.
   */
  public JSONObject commit() {
    return finish("commit");
  }

  /**
   * Ends the session and discards what it wrote, returning the {@code committed} frame.
   * <p>
   * Only a {@code per_stream} session can genuinely undo chunks it has already acknowledged; the answer's
   * {@code summary.partialCommit} says so. A session on an externally-managed transaction discards nothing here
   * either - see {@link #commit()}.
   */
  public JSONObject rollback() {
    return finish("rollback");
  }

  /**
   * Rolls the session back if it is still open, then closes the connection. Idempotent, so it is safe as the
   * resource-block exit after an explicit {@link #commit()}.
   */
  @Override
  public void close() {
    if (open) {
      try {
        rollback();
      } catch (final Exception e) {
        LogManager.instance().log(this, Level.FINE, "Error on rolling back /ws insert session %s while closing", e,
            sessionId);
      }
    }

    try {
      webSocket.sendClose(WebSocket.NORMAL_CLOSURE, "").orTimeout(timeoutMs, TimeUnit.MILLISECONDS).join();
    } catch (final Exception e) {
      webSocket.abort();
    }
  }

  private JSONObject finish(final String action) {
    checkOpen();
    final JSONObject frame = new JSONObject();
    frame.put("action", action);
    frame.put("sessionId", sessionId);
    try {
      return exchange(frame, "committed");
    } finally {
      // Closed whatever the server said: a commit the engine refused has already rolled the session back, and a
      // second frame on it would only be answered "session is closed".
      open = false;
    }
  }

  /**
   * Writes one frame and reads the one answer to it.
   * <p>
   * Every frame this class sends is answered by exactly one frame, so anything else waiting in the queue is an
   * unsolicited {@code error} - the idle sweep having given up on the session - and is reported rather than
   * skipped over: whatever the answer to the current frame would have said, the session is gone.
   */
  private JSONObject exchange(final JSONObject frame, final String expectedAction) {
    send(frame);

    final String raw = awaitFrame();
    final JSONObject answer = new JSONObject(raw);
    if ("error".equals(answer.getString("result", ""))) {
      final String detail = answer.getString("detail", answer.getString("error", "unknown error"));
      throw new RemoteException("Error on /ws insert session '" + sessionId + "': " + detail);
    }

    final String action = answer.getString("action", "");
    if (!expectedAction.equals(action))
      throw new RemoteException(
          "Unexpected frame '" + action + "' on /ws insert session '" + sessionId + "', expected '" + expectedAction + "'");

    return answer;
  }

  private void send(final JSONObject frame) {
    try {
      webSocket.sendText(frame.toString(), true).orTimeout(timeoutMs, TimeUnit.MILLISECONDS).join();
    } catch (final Exception e) {
      open = false;
      throw new RemoteException("Error on sending a /ws insert frame for session '" + sessionId + "'", e);
    }
  }

  private String awaitFrame() {
    try {
      final String raw = incoming.poll(timeoutMs, TimeUnit.MILLISECONDS);
      if (raw != null)
        return raw;
    } catch (final InterruptedException e) {
      Thread.currentThread().interrupt();
      open = false;
      throw new RemoteException("Interrupted while waiting for a /ws insert frame on session '" + sessionId + "'", e);
    }

    open = false;
    final Throwable failure = listener.getFailure();
    if (failure != null)
      throw new RemoteException("The /ws connection of insert session '" + sessionId + "' failed", failure);
    if (listener.isClosed())
      throw new RemoteException("The server closed the /ws connection of insert session '" + sessionId + "'");
    throw new RemoteException(
        "Timeout of " + timeoutMs + "ms waiting for the answer to a frame of /ws insert session '" + sessionId + "'");
  }

  private void checkOpen() {
    if (!open)
      throw new RemoteException("The /ws insert session '" + sessionId + "' is closed");
  }

  /**
   * The listener the JDK client hands frames to. Text frames arrive possibly split, so parts are accumulated
   * until the one flagged last; a whole frame is then queued for {@link #awaitFrame()} to pick up.
   */
  static final class RemoteWebSocketListener implements WebSocket.Listener {
    private final LinkedBlockingQueue<String> queue  = new LinkedBlockingQueue<>();
    private final StringBuilder               buffer = new StringBuilder();
    private volatile Throwable                failure;
    private volatile boolean                  closed;

    LinkedBlockingQueue<String> getQueue() {
      return queue;
    }

    Throwable getFailure() {
      return failure;
    }

    boolean isClosed() {
      return closed;
    }

    @Override
    public void onOpen(final WebSocket webSocket) {
      webSocket.request(1);
    }

    @Override
    public CompletionStage<?> onText(final WebSocket webSocket, final CharSequence data, final boolean last) {
      buffer.append(data);
      if (last) {
        queue.offer(buffer.toString());
        buffer.setLength(0);
      }
      webSocket.request(1);
      return null;
    }

    @Override
    public CompletionStage<?> onClose(final WebSocket webSocket, final int statusCode, final String reason) {
      closed = true;
      return null;
    }

    @Override
    public void onError(final WebSocket webSocket, final Throwable error) {
      failure = error;
      closed = true;
    }
  }

  /**
   * Opens a {@link RemoteInsertSession}. Obtained from {@link RemoteDatabase#newInsertSession()}, which is what
   * binds it to the server, the credentials and the database of that connection.
   */
  public static class Builder {
    private final RemoteDatabase     database;
    private       String             sessionId;
    private       String             targetType;
    private       String             transactionMode;
    private       String             conflictMode;
    private       List<String>       keyColumns;
    private       List<String>       updateColumnsOnConflict;
    private       boolean            validateOnly;
    private       String             transactionId;
    private       Consumer<JSONObject> ackListener;
    private       long               timeoutMs = 60_000L;

    Builder(final RemoteDatabase database) {
      this.database = database;
    }

    /** The id to open the session under. Left out, the server generates one; see {@link #getSessionId()}. */
    public Builder sessionId(final String sessionId) {
      this.sessionId = sessionId;
      return this;
    }

    /** Default type of every record, overridable per record with {@code @class}. */
    public Builder targetType(final String targetType) {
      this.targetType = targetType;
      return this;
    }

    /** One of {@code per_stream} (the default), {@code per_batch}, {@code per_row}, {@code none}. */
    public Builder transactionMode(final String transactionMode) {
      this.transactionMode = transactionMode;
      return this;
    }

    /** One of {@code error} (the default), {@code update}, {@code ignore}, {@code abort}. */
    public Builder conflictMode(final String conflictMode) {
      this.conflictMode = conflictMode;
      return this;
    }

    public Builder keyColumns(final List<String> keyColumns) {
      this.keyColumns = keyColumns;
      return this;
    }

    public Builder updateColumnsOnConflict(final List<String> updateColumnsOnConflict) {
      this.updateColumnsOnConflict = updateColumnsOnConflict;
      return this;
    }

    /** Rows are received, parsed and counted, and nothing is written. */
    public Builder validateOnly(final boolean validateOnly) {
      this.validateOnly = validateOnly;
      return this;
    }

    /**
     * Has the session write into the transaction the {@link RemoteDatabase} it was obtained from has already
     * begun, instead of opening one of its own (issue #7403). The rows become durable when that database's
     * {@link RemoteDatabase#commit()} runs, and its {@link RemoteDatabase#rollback()} undoes them.
     *
     * @throws RemoteException when the database is not inside a transaction, since there would be nothing to join
     */
    public Builder joinCurrentTransaction() {
      final String currentSession = database.getSessionId();
      if (currentSession == null)
        throw new RemoteException(
            "The database has no open transaction to join: call begin() before opening the insert session");
      this.transactionId = currentSession;
      this.transactionMode = "none";
      return this;
    }

    /** Invoked with every {@code batchAck} before {@link #sendChunk(List)} returns it. */
    public Builder onBatchAck(final Consumer<JSONObject> ackListener) {
      this.ackListener = ackListener;
      return this;
    }

    /** How long a single frame exchange may take before it is given up on. Default is 60 seconds. */
    public Builder timeout(final long timeoutMs) {
      this.timeoutMs = timeoutMs;
      return this;
    }

    /**
     * Connects, sends the {@code start} frame and returns the session the server answered {@code started} with.
     *
     * @throws RemoteException when the connection or the {@code start} frame is refused
     */
    public RemoteInsertSession open() {
      final JSONObject options = new JSONObject();
      if (targetType != null)
        options.put("targetType", targetType);
      if (transactionMode != null)
        options.put("transactionMode", transactionMode);
      if (conflictMode != null)
        options.put("conflictMode", conflictMode);
      if (keyColumns != null)
        options.put("keyColumns", new JSONArray(keyColumns));
      if (updateColumnsOnConflict != null)
        options.put("updateColumnsOnConflict", new JSONArray(updateColumnsOnConflict));
      if (validateOnly)
        options.put("validateOnly", true);

      final JSONObject start = new JSONObject();
      start.put("action", "start");
      start.put("database", database.getName());
      if (sessionId != null)
        start.put("sessionId", sessionId);
      if (transactionId != null)
        start.put("transactionId", transactionId);
      start.put("options", options);

      final RemoteWebSocketListener listener = new RemoteWebSocketListener();
      final URI uri = URI.create(database.getWebSocketUrl());

      final WebSocket webSocket;
      try {
        webSocket = database.getHttpClient().newWebSocketBuilder()
            .header("Authorization", database.getBasicAuthorizationHeader())
            .connectTimeout(Duration.ofMillis(timeoutMs))
            .buildAsync(uri, listener)
            .orTimeout(timeoutMs, TimeUnit.MILLISECONDS)
            .join();
      } catch (final Exception e) {
        throw new RemoteException("Error on opening the /ws insert session on " + uri, e);
      }

      // The session object is what knows how to read an answer, so 'started' is exchanged through a throwaway
      // one bound to the same socket rather than by duplicating the queue handling here.
      final RemoteInsertSession handshake = new RemoteInsertSession(webSocket, listener,
          new JSONObject().put("sessionId", sessionId == null ? "<pending>" : sessionId), null, timeoutMs);
      final JSONObject started;
      try {
        started = handshake.exchange(start, "started");
      } catch (final RuntimeException e) {
        webSocket.abort();
        throw e;
      }

      return new RemoteInsertSession(webSocket, listener, started, ackListener, timeoutMs);
    }
  }
}
