  @Override
  public ResultSet executeDDL(final CommandContext context) {
    final Database db = context.getDatabase();
    final DocumentType typez = db.getSchema().getType(typeName.getStringValue());

    if (typez == null)
      throw new CommandExecutionException("Type name is null");

    final Property property = typez.getProperty(propertyName.getStringValue());
    if (property == null)
      throw new SchemaException("Property '" + propertyName + "' not found on type " + typez);

    final ResultInternal result = new ResultInternal(context.getDatabase());
    result.setProperty("type", typeName.getStringValue());
    result.setProperty("property", propertyName.getStringValue());

    if (customPropertyName != null) {
      final String customName = customPropertyName.getStringValue();
      final Object oldValue = property.getCustomValue(customName);
      final Object finalValue = customPropertyValue.execute((Identifiable) null, context);
      property.setCustomValue(customName, finalValue);

      result.setProperty("operation", "alter property custom");
      result.setProperty("customAttribute", customPropertyName.getStringValue());
      result.setProperty("oldValue", oldValue);
      result.setProperty("newValue", finalValue);
    } else if (settingName != null) {
      final String setting = settingName.getStringValue().toLowerCase(Locale.ENGLISH);
      // The setting is checked BEFORE its value is evaluated (issue #11803): an unsupported one used to be reported only after
      // the value had been, so 'TYPE LONG' was refused for its bare-word value with the advice to quote it, and the quoted form
      // was then refused for the setting - the advice led to a second failure. A setting no ALTER PROPERTY supports is a
      // statement that cannot be run, so it is refused as one
      requireSupportedSetting(setting, typez, property);
      // NAME is read as an identifier - getDefaultAlias() resolves a bare `NAME newName` (mirroring ALTER TYPE ...
      // NAME) or a backtick-quoted `NAME \`odd name\`` to the plain, unescaped name - rather than as an evaluated
      // expression, so it is taken literally rather than resolved as a variable reference, and any backtick
      // quoting is unescaped instead of being stored as part of the property name.
      final Object finalValue = settingValue == null ? valueOfMissingValue(setting)
          : "name".equalsIgnoreCase(setting) ? settingValue.getDefaultAlias().getStringValue()
          : "default".equalsIgnoreCase(setting) ? settingValue.toString() : PropertyAttributeValues.evaluate(setting, settingValue, context);

      final Object oldValue;

      if ("name".equalsIgnoreCase(setting)) {
        oldValue = property.getName();
        typez.renameProperty(propertyName.getStringValue(), String.valueOf(finalValue));
      } else if ("readonly".equalsIgnoreCase(setting)) {
        oldValue = property.isReadonly();
        property.setReadonly(PropertyAttributeValues.asBoolean(setting, finalValue));
      } else if ("mandatory".equalsIgnoreCase(setting)) {
        oldValue = property.isMandatory();
        final boolean mandatory = PropertyAttributeValues.asBoolean(setting, finalValue);
        if (mandatory && !property.isMandatory())
          ExistingRecordsCheck.requireExistence(db, typez, property.getName(), true, false);
        property.setMandatory(mandatory);
      } else if ("notnull".equalsIgnoreCase(setting)) {
        oldValue = property.isNotNull();
        final boolean notNull = PropertyAttributeValues.asBoolean(setting, finalValue);
        if (notNull && !property.isNotNull())
          ExistingRecordsCheck.requireExistence(db, typez, property.getName(), false, true);
        property.setNotNull(notNull);
      } else if ("hidden".equalsIgnoreCase(setting)) {
        oldValue = property.isHidden();
        property.setHidden(PropertyAttributeValues.asBoolean(setting, finalValue));
      } else if ("external".equalsIgnoreCase(setting)) {
        oldValue = property.isExternal();
        property.setExternal(PropertyAttributeValues.asBoolean(setting, finalValue));
      } else if ("compression".equalsIgnoreCase(setting)) {
        oldValue = property.getCompression();
        // null clears, as in CREATE PROPERTY: the text "null" is not a compression (issue #10099)
        property.setCompression(PropertyAttributeValues.asText(finalValue));
      } else if ("max".equalsIgnoreCase(setting)) {
        oldValue = property.getMax();
        requireStoredValuesWithin(db, typez, property, finalValue, null, "" + finalValue, null, "MAX " + finalValue);
        // MAX null clears the bound, it does not store the text "null" (#9172)
        property.setMax(finalValue == null ? null : "" + finalValue);
      } else if ("min".equalsIgnoreCase(setting)) {
        oldValue = property.getMin();
        requireStoredValuesWithin(db, typez, property, finalValue, "" + finalValue, null, null, "MIN " + finalValue);
        property.setMin(finalValue == null ? null : "" + finalValue);
      } else if ("default".equalsIgnoreCase(setting)) {
        // Issue #6134: report the definition rather than evaluating the outgoing default. Evaluating it would make
        // ALTER PROPERTY - the one statement that can repair a broken default - fail on exactly the schemas that
        // need repairing.
        oldValue = property.getDefaultValueDefinition();
        property.setDefaultValue("" + finalValue);
      } else if ("regexp".equalsIgnoreCase(setting)) {
        oldValue = property.getRegexp();
        requireStoredValuesWithin(db, typez, property, finalValue, null, null, "" + finalValue, "REGEXP " + finalValue);
        property.setRegexp(finalValue == null ? null : "" + finalValue);
      } else {
        // unreachable: requireSupportedSetting() refused it above. Kept for a setting added there without an arm here
        throw new CommandSQLParsingException("Setting '" + setting + "' not supported");
      }

      result.setProperty("operation", "alter property");
      result.setProperty("attribute", setting);
      result.setProperty("oldValue", oldValue);
      result.setProperty("newValue", finalValue);
    } else
      // neither a custom attribute nor a setting: the statement says nothing to alter (the property was found above)
      throw new CommandExecutionException("ALTER PROPERTY " + typez.getName() + "." + property.getName() + " names neither a setting nor a custom attribute to alter");

    final InternalResultSet rs = new InternalResultSet();
    rs.add(result);
    return rs;
  }

  /**
   * The value of an attribute the statement named without one. The grammar lets the value of an attribute be absent
   * ({@code identifier expression?}), and the engine's own rule for an absent value is that it means true for a flag
   * attribute: {@code CREATE PROPERTY ... (MANDATORY)} sets the flag, and the parser says so in as many words ("If no
   * value specified, leave settingValue as null (implies true for boolean flags)"). ALTER PROPERTY dereferenced the
   * absent value instead, and the statement answered a server fault (HTTP 500) for a mistake the statement alone
   * decides (issue #13030).
   * <p>
   * An attribute that takes a value says so, instead of failing the same way: the same message CREATE PROPERTY
   * gives for a DEFAULT without one, and a parsing exception, so the statement answers a client error (400). The
   * status the refusals of a wrong value answer is #12809's subject.
   *
   * @param setting the attribute the statement named, in lower case
   * @return the value of the attribute
   */
  private static Object valueOfMissingValue(final String setting) {
    if (FLAG_SETTINGS.contains(setting))
      return Boolean.TRUE;
    if ("default".equals(setting))
      throw new CommandSQLParsingException("Default value not set");
    throw new CommandSQLParsingException(setting.toUpperCase(Locale.ENGLISH) + " takes a value");
  }

  /**
   * Refuses a setting ALTER PROPERTY cannot change, naming the ones it can. The TYPE of a property gets its own answer, since it
   * is the one a caller most often reaches for: a property's type is fixed when it is created, because the records already
   * hold values of that type and its indexes are keyed on it.
   */
  private static void requireSupportedSetting(final String setting, final DocumentType type, final Property property) {
    if (SUPPORTED_SETTINGS.contains(setting))
      return;

    final String supported = String.join(", ", SUPPORTED_SETTINGS).toUpperCase(Locale.ENGLISH);
    if ("type".equals(setting))
      throw new CommandSQLParsingException(
          "The type of property " + type.getName() + "." + property.getName() + " cannot be changed: a property keeps the type it "
              + "was created with. To change it, create a property of the new type, copy the values with UPDATE " + type.getName()
              + " SET <newProperty> = " + property.getName() + ", drop the old property (with FORCE to drop its indexes too), "
              + "rename the new one and recreate the indexes on it. ALTER PROPERTY can change " + supported);

    throw new CommandSQLParsingException("Setting '" + setting + "' not supported by ALTER PROPERTY, which can change " + supported
        + ", or a custom attribute with CUSTOM <name> = <value>");
  }

  /**
   * Refuses to add a MIN, MAX or REGEXP over records that already violate it (#9112). Clearing the bound
   * ({@code null}) needs no scan.
   */
  private static void requireStoredValuesWithin(final Database db, final DocumentType type, final Property property,
      final Object newValue, final String min, final String max, final String regexp, final String what) {
    if (newValue == null)
      return;
    DocumentValidator.requireReadableBound(db, type, property, min, "MIN");
    DocumentValidator.requireReadableBound(db, type, property, max, "MAX");
    // compiled first, so an invalid pattern is reported as one before it is judged against the type
    final StoredValueConstraints constraints = StoredValueConstraints.of(db, false, min, max, regexp);
    // before the scan: a pattern the type cannot use is refused for what it is, not for the first record it meets (#9808)
    DocumentValidator.requireUsableRegexp(db, type, property, regexp);
    ExistingRecordsCheck.requireValues(db, type, property, constraints, what);
  }

