package com.arcadedb.query.sql.parser;

/**
 * {@link SimpleNode#SimpleNode(int)} never reads its {@code id} argument, so {@link Limit} and {@link Timeout} pass these
 * constants only to keep a stable, distinct marker at each call site - the actual values are otherwise meaningless. They used to
 * be two entries out of ~370 generated by the retired JavaCC/JJTree grammar; that generator and the rest of its table are gone
 * (issue #5867), so this interface is now hand-maintained and limited to the two values still referenced.
 * DO NOT try to wire a JavaCC generator back to this file - it is hand-maintained.
 *
 * @author Luca Garulli (l.garulli@arcadedata.com)
 */
public interface SqlParserTreeConstants {
  // marker ids only, must stay distinct from each other - do not regenerate from a JavaCC grammar
  int JJTLIMIT   = 108;
  int JJTTIMEOUT = 111;
}
