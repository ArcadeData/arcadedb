  @Override
  public ResultSet executeDDL(final CommandContext context) {
    final Database db = context.getDatabase();
    final Schema schema = db.getSchema();
    final DocumentType typez = schema.getType(typeName.getStringValue());
    if (typez == null) {
      throw new CommandExecutionException("Schema Class not found: " + typeName);
    }

    final long recs = context.getDatabase().countType(typeName.getStringValue(), polymorphic);
    if (recs > 0 && !unsafe) {
      if (typez.isSubTypeOf("V")) {
        throw new CommandExecutionException(
            "'TRUNCATE TYPE' command cannot be used on not empty vertex classes. Apply the 'UNSAFE' keyword to force it (at your own risk)");
      } else if (typez.isSubTypeOf("E")) {
        throw new CommandExecutionException(
            "'TRUNCATE TYPE' command cannot be used on not empty edge classes. Apply the 'UNSAFE' keyword to force it (at your own risk)");
      }
    }

    final InternalResultSet rs = new InternalResultSet();
    final Collection<DocumentType> subTypes = typez.getSubTypes();
    if (polymorphic && !unsafe) {// for multiple inheritance
      for (final DocumentType subType : subTypes) {
        final long subTypeRecs = context.getDatabase().countType(typeName.getStringValue(), false);
        if (subTypeRecs > 0) {
          if (subType.isSubTypeOf("V")) {
            throw new CommandExecutionException("'TRUNCATE TYPE' command cannot be used on not empty vertex classes (" + subType.getName()
                + "). Apply the 'UNSAFE' keyword to force it (at your own risk)");
          } else if (subType.isSubTypeOf("E")) {
            throw new CommandExecutionException("'TRUNCATE TYPE' command cannot be used on not empty edge classes (" + subType.getName()
                + "). Apply the 'UNSAFE' keyword to force it (at your own risk)");
          }
        }
      }
    }

    final boolean transactional = db.isTransactionActive();
    if (transactional)
      truncateInCallerTransaction(db);
    else
      truncateInOwnTransaction(db, schema, typez);

    final ResultInternal result = new ResultInternal(context.getDatabase());
    result.setProperty("operation", "truncate type");
    result.setProperty("typeName", typeName.getStringValue());
    // Which of the two paths ran, so a caller can tell whether its ROLLBACK will put the records back. The old
    // behaviour was indistinguishable from the transactional one right up to the rollback that silently kept most of
    // the deletes (issue #6220), and an answer nobody can read is half a fix.
    result.setProperty("transactional", transactional);
    rs.add(result);

    return rs;
  }

  /**
   * The caller owns the transaction, so this is one more operation inside it: every record is deleted in that
   * transaction, with the indexes maintained per record exactly as {@code DELETE FROM} does, and a {@code ROLLBACK}
   * puts all of them back (issue #6220).
   * <p>
   * Neither of the two speed-ups the {@linkplain #truncateInOwnTransaction own-transaction path} uses is available
   * here, and both for the same reason: they commit. Dropping the indexes is a schema change, which
   * {@code LocalSchema.recordFileChanges} applies immediately; batching means calling {@code commit()} on the
   * caller's transaction. Either one turns a subsequent {@code ROLLBACK} into a partial, silent data loss.
   */
  private void truncateInCallerTransaction(final Database db) {
    final RuntimeException failure = TruncateRecordDeleter.deleteAll(db, 0,
        callback -> db.scanType(typeName.getStringValue(), polymorphic, callback::test));

    // Report the failure rather than a partial truncate masquerading as success (issue #4817). The caller's
    // transaction is left untouched, so its own rollback undoes the deletes that did happen.
    if (failure != null)
      throw failure;
  }

  /**
   * No transaction was active, so the statement owns one and can use the fast path: drop the indexes, delete the
   * records in small committed batches, rebuild the (empty) indexes.
   * <p>
   * The index drop/rebuild is not only a speed-up (issue #4352): scanning + record-by-record delete with an in-loop
   * batched commit can leave LSM-Tree indexes full of stale tombstones, so the index ends up in an inconsistent state
   * (infinite-loop iteration, spurious duplicate-key errors). Dropping the indexes, clearing the records and
   * recreating the (empty) indexes is both faster and safer - and it is only ever correct here, where no caller
   * transaction can be committed through.
   */
  private void truncateInOwnTransaction(final Database db, final Schema schema, final DocumentType typez) {
    // Capture index definitions BEFORE truncating records: the drop below is a committed schema change and the
    // definitions are all that is left to rebuild from.
    final List<IndexDefinition> indexDefs = collectIndexDefinitions(typez, polymorphic);
    for (final IndexDefinition def : indexDefs)
      schema.dropIndex(def.name);

    final int batchSize = Math.max(1, db.getConfiguration().getValueAsInteger(GlobalConfiguration.TRUNCATE_BATCH_SIZE));

    final RuntimeException failure = TruncateRecordDeleter.deleteAllInOwnTransaction(db, batchSize,
        callback -> db.scanType(typeName.getStringValue(), polymorphic, callback::test),
        deletionFailure -> rebuildIndexes(db, schema, indexDefs, deletionFailure),
        "TYPE '" + typeName.getStringValue() + "'");

    // Report the failure rather than a partial truncate masquerading as success (issue #4817).
    if (failure != null)
      throw failure;
  }

  /**
   * Recreates the indexes dropped at the start of {@link #truncateInOwnTransaction}, inside that method's
   * transaction and before it is closed.
   * <p>
   * They are rebuilt in <b>every</b> case: on success they start empty since all records are gone; on failure they
   * are rebuilt over whatever records remain, so the schema is never left without the indexes it had - the
   * {@code dropIndex} is a committed schema change and nothing later can undo it. A subsequent retry/run re-drops
   * and re-empties them.
   * <p>
   * The rebuild survives the rollback that a failure triggers, and has to: the {@code dropIndex} above is a committed
   * schema change that nothing later can undo, so a rebuild discarded with the failing transaction would leave the
   * type carrying an EMPTY index over records that are all still there.
   *
   * @return the failure to carry on with: the one passed in, or the first rebuild failure when there was none.
   */
  private RuntimeException rebuildIndexes(final Database db, final Schema schema, final List<IndexDefinition> indexDefs,
      RuntimeException deletionFailure) {
    if (indexDefs.isEmpty())
      // Nothing to rebuild, so the deletion transaction is left exactly as it was for the caller to decide.
      return deletionFailure;

    // CLOSE OUT THE DELETION TRANSACTION FIRST, in whichever direction the outcome calls for: commit when the deletes
    // are good, so the build sees the empty buckets instead of repopulating the index with records that are logically
    // deleted but not yet flushed; roll back when they are not, so it sees the state that is going to survive.
    //
    // Either way the rebuild must not run INSIDE a transaction whose fate somebody else is about to decide, because a
    // build's entries now commit with the transaction it runs in (issue #6324, item 1): a rebuild left in the failing
    // one would be built and then thrown away with it, leaving the type with the empty index the committed drop had
    // already reduced it to. Deciding it here is also what leaves TruncateRecordDeleter with no transaction of its
    // own to close, which is the point.
    if (db.isTransactionActive()) {
      try {
        if (deletionFailure == null)
          db.commit();
        else
          db.rollback();
      } catch (final RuntimeException e) {
        if (deletionFailure == null)
          deletionFailure = e;
        else
          deletionFailure.addSuppressed(e);
      }
    }

    // Every definition is attempted, and one that cannot be recreated does not take the others with it. Each
    // create() opens and commits its own transaction, so abandoning the loop at the first failure would leave the
    // type missing indexes that had nothing wrong with them - the opposite of what rebuilding on failure at all is for.
    for (final IndexDefinition def : indexDefs) {
      try {
        recreateIndex(schema, def);
      } catch (final RuntimeException e) {
        if (deletionFailure == null)
          deletionFailure = e;
        else
          deletionFailure.addSuppressed(e);
      }
    }

    return deletionFailure;
  }

  private void recreateIndex(final Schema schema, final IndexDefinition def) {
    // withType() may swap the builder to a type-specific subclass (e.g. TypeLSMVectorIndexBuilder
    // for LSM_VECTOR), so call it first and keep the returned reference instead of chaining.
    final TypeIndexBuilder builder = schema.buildTypeIndex(def.typeName, def.propertyNames).withType(def.indexType);
    builder.withUnique(def.unique);
    builder.withPageSize(def.pageSize);
    builder.withNullStrategy(def.nullStrategy);

    // Type-specific metadata (e.g. LSM_VECTOR dimensions/similarity) must be carried over,
    // otherwise the recreated index loses its configuration and inserts fail with "index
    // dimension 0" (issue #4359). The type-specific builder's withMetadata(IndexMetadata)
    // override reinstates the vector-specific fields.
    if (def.indexType == Schema.INDEX_TYPE.LSM_VECTOR && def.metadata instanceof LSMVectorIndexMetadata vectorMeta)
      // A copy - rather than the original reference - keeps the dropped index's per-index runtime state (notably
      // buildState) off the rebuilt one and resets associatedBucketId so the per-bucket builder sets it during create().
      ((TypeLSMVectorIndexBuilder) builder).withMetadata(vectorMeta.copy(def.typeName, def.propertyNames, -1));

    builder.create();
  }

  private static List<IndexDefinition> collectIndexDefinitions(final DocumentType typez, final boolean polymorphic) {
    final List<IndexDefinition> defs = new ArrayList<>();
    final Set<String> seen = new HashSet<>();
    for (final TypeIndex index : typez.getAllIndexes(false))
      if (seen.add(index.getName()))
        defs.add(IndexDefinition.from(index));
    if (polymorphic)
      for (final DocumentType sub : typez.getSubTypes())
        for (final TypeIndex index : sub.getAllIndexes(false))
          if (seen.add(index.getName()))
            defs.add(IndexDefinition.from(index));
    return defs;
  }

