package com.arcadedb.query.opencypher;

/**
 * The executor binds anonymous pattern elements, and a few clause-private flags, to generated
 * variables that the query never named: {@code   src0}, {@code   tgt0}, {@code   rel0},
 * {@code   nd0}, {@code   __anon0}, {@code   wasCreated}. They all begin with the two-space prefix
 * below, which no Cypher identifier can start with, so the prefix is a reliable marker.
 * <p>
 * These bindings are execution state, not query variables: they must never reach the user, in
 * particular through {@code RETURN *} or the distinctness key of {@code RETURN DISTINCT *}
 * (issue #5444).
 *
 * @author Luca Garulli (l.garulli@arcadedata.com)
 */
public final class InternalVariables {
  /**
   * Prefix marking a variable generated by the executor rather than written by the query.
   */
  public static final String PREFIX = "  ";

  private InternalVariables() {
  }

  /**
   * Returns true if the given variable name was generated by the executor and must stay invisible to
   * the caller.
   */
  public static boolean isInternal(final String variableName) {
    return variableName != null && variableName.startsWith(PREFIX);
  }
}
